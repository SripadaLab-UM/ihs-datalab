"""A person's own changes to the pipelines repo: the Pipelines tab's Edit
manually, New file, and Edit before accepting on an assistant's proposal.

No agent is involved. A person's edit is a proposal like the agent's, and
goes through the same steps, only its files come from the person's editor:

- **What can be changed.** Exactly what an agent's proposal may change
  (`proposal_problem`): files in `ihsDataR/` and `workflows/`, never
  `.github/`, with names every disk takes, plain text under the size limit.
  Files roxygen2 writes (`ihsDataR/man/*.Rd`, `NAMESPACE`) aren't edited by
  hand: `source_note` says where they come from.
- **Where it starts.** GitHub's `main` as last synced (for Edit before
  accepting, the proposal's own base): the edit's base, its "where you
  started". One open edit of a file at a time: opening the file again finds it.
- **Keep as a draft.** The files are kept in DataLab's database, on this
  computer, until the person shares or discards them. Each time, DataLab
  makes a commit of the base with the person's files (never pushed): its
  tree is what the tests run on, as a proposal's.
- **The check and the tests** are the proposal's: check.py (with the
  workflow check on workflow files), and the package's tests in the
  no-network container (testing.py).
- **Save & share** is share.save_and_share, as for a proposal, committed as
  the signed-in person with a `DataLab-Edit` trailer, but strict: if a file
  of the edit changed on GitHub since it began, it stops with a conflict
  instead of merging. The person sees their edit, the version now on
  GitHub, and where they started, and chooses: reapply their edit on the
  new version (a three-way merge; overlapping lines they resolve
  themselves), or write the text to keep. Nothing is overwritten silently.
- **Edit before accepting.** An assistant's proposal becomes the person's
  edit: its files, as the agent left them, on the proposal's base. The
  proposal is marked superseded (it names the edit), and its conversation's
  base moves on, as when it's discarded, so the agent's next proposal holds
  only what it changes after this.
"""

