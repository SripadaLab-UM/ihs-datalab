def test_discarding_shares_nothing_and_frees_the_file(lab):
    synced(lab)
    before = lab.remote.head()
    edit = keep(lab, start(lab), {STEPS: NEW_STEPS})
    gone = lab.client.post(f"/api/pipelines/edits/{edit['id']}/discard").json()
    assert gone["status"] == "discarded" and lab.remote.head() == before
    late = lab.client.post(f"/api/pipelines/edits/{edit['id']}/share", json={"version": None})
    assert late.status_code == 409
    listed = lab.client.get("/api/pipelines/edits").json()
    assert [(e["id"], e["status"]) for e in listed] == [(edit["id"], "discarded")]
    assert start(lab)["id"] != edit["id"]


def test_a_save_cut_off_by_datalab_stopping_says_so(lab):
    synced(lab)
    edit = lab.pipelines.edits.get(start(lab)["id"])
    lab.pipelines.edits.store.update(edit, status="saving")
    assert lab.pipelines.edits.store.end_interrupted() == 1
    found = lab.pipelines.edits.get(edit.id)
    assert found.status == "failed" and "stopped while saving" in found.result["message"]


def test_practice_datalab_has_no_edits(tmp_path, github_keychain):
    settings = Settings(profile="practice", data_dir=tmp_path / "data", oracle=None)
    connection = db.connect(settings.database_file)
    store = ConversationStore(connection)
    manager = SessionManager(settings, store, SessionTokens())
    router = build_pipelines_router(
        PipelineServices(settings, connection, store, manager, auth=None, sandbox=FakeSandbox())
    )
    app = FastAPI()
    app.include_router(router)
    with TestClient(app) as client:
        status = client.get("/api/pipelines/status").json()
        assert (status["available"], status["practice"]) == (False, True)
        refused = client.post("/api/pipelines/edits", json={"path": STEPS})
        assert refused.status_code == 409 and "Practice" in refused.json()["detail"]
        assert client.get("/api/pipelines/edits").status_code == 409
    connection.close()
