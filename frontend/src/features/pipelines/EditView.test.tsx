it("shows the three versions when GitHub changed the file, and reapplies the edit", async () => {
  const changed = edit({
    status: "conflict",
    upstream_changed: true,
    result: { state: "conflict", message: "Someone changed ihsDataR/R/steps.R on GitHub since you started.", findings: [], conflicts: [STEPS], after_rebase: false },
    files: [{ ...edit().files[0], text: "a <- 10\n", before: "a <- 1\n", upstream_changed: true, theirs: "a <- 12\n" }],
  }); // prettier-ignore
  vi.mocked(pipelinesApi.startEdit).mockResolvedValue(changed);
  vi.mocked(pipelinesApi.reapplyEdit)
    .mockResolvedValueOnce({ edit: changed, merged: { [STEPS]: "<<<<<<< Your edit\na <- 10\n=======\na <- 12\n>>>>>>> The version now on GitHub\n" } })
    .mockResolvedValueOnce({ edit: edit({ files: [{ ...edit().files[0], text: "a <- 13\n", before: "a <- 12\n" }] }), merged: {} });
  open();
  const box = await screen.findByRole("region", { name: "Changed on GitHub since you started" });
  expect(within(box).getByLabelText(`The version now on GitHub: ${STEPS}`)).toHaveValue("a <- 12\n");
  expect(within(box).getByLabelText(`Where you started: ${STEPS}`)).toHaveValue("a <- 1\n");
  expect(within(box).getByLabelText(`Your edit: ${STEPS}`)).toHaveValue("a <- 10\n");
  expect(screen.getByRole("button", { name: "Save & share" })).toBeDisabled();
  fireEvent.click(within(box).getByRole("button", { name: "Reapply my edit on the new version" }));
  const resolve = await within(box).findByLabelText(`The version to keep of ${STEPS}`);
  const use = within(box).getByRole("button", { name: "Use this text on the new version" });
  expect(use).toBeDisabled(); // the overlap markers are still there
  fireEvent.change(resolve, { target: { value: "a <- 13\n" } });
  fireEvent.click(use);
  await waitFor(() => expect(pipelinesApi.reapplyEdit).toHaveBeenLastCalledWith("pe_1", "v1", { [STEPS]: "a <- 13\n" }));
  await waitFor(() => expect(screen.queryByRole("region", { name: "Changed on GitHub since you started" })).toBeNull());
  expect(source()).toHaveValue("a <- 13\n");
});

it("edits an assistant's proposal before accepting it: it becomes the person's edit", async () => {
  const detail: PipelineProposalDetail = {
    proposal: {
      id: "pp_1", conversation_id: "c1", conversation_title: "Weekly steps", status: "open", created_at: "t", updated_at: "t",
      turn: 2, base: "abc1234def", files: [{ path: STEPS, change: "modified" }], refused: [], result: null, commit: null,
      decided_by: null, test: null,
    },
    files: [{ path: STEPS, change: "modified", before: R, after: "x\n", binary: false, diff: "" }],
    findings: [],
  }; // prettier-ignore
  vi.mocked(pipelinesApi.proposal).mockResolvedValue(detail);
  vi.mocked(pipelinesApi.editProposal).mockResolvedValue(
    edit({ id: "pe_9", origin: { proposal_id: "pp_1", conversation_id: "c1", conversation_title: "Weekly steps" } }),
  );
  const onEdit = vi.fn();
  client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  const proposalView = render(
    <QueryClientProvider client={client}>
      <ProposalView id="pp_1" onBack={vi.fn()} onEdit={onEdit} />
    </QueryClientProvider>,
  );
  expect(await screen.findByText("Suggested by the assistant")).toBeInTheDocument();
  fireEvent.click(screen.getByRole("button", { name: /Edit before accepting/ }));
  await waitFor(() => expect(onEdit).toHaveBeenCalledWith("pe_9"));
  expect(pipelinesApi.editProposal).toHaveBeenCalledWith("pp_1");
  proposalView.unmount();

  // Opened, the edit says where it came from, and links back to the suggestion.
  vi.mocked(pipelinesApi.getEdit).mockResolvedValue(
    edit({ id: "pe_9", origin: { proposal_id: "pp_1", conversation_id: "c1", conversation_title: "Weekly steps" } }),
  );
  const onOpenProposal = vi.fn();
  open({ id: "pe_9" }, { onOpenProposal });
  expect(await screen.findByText(/From a change suggested by the assistant/)).toBeInTheDocument();
  expect(screen.getByText(/Weekly steps/)).toBeInTheDocument();
  fireEvent.click(screen.getByRole("button", { name: "See what it suggested" }));
  expect(onOpenProposal).toHaveBeenCalledWith("pp_1");
});

