function open(target: Parameters<typeof EditView>[0]["target"] = { path: STEPS }, more: Partial<Parameters<typeof EditView>[0]> = {}) {
  client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  const onClose = vi.fn();
  const view = render(
    <MemoryRouter>
      <QueryClientProvider client={client}>
        <EditView target={target} repo="SripadaLab-UM/ihs-pipelines" signedIn onClose={onClose} {...more} />
      </QueryClientProvider>
    </MemoryRouter>,
  );
  return { ...view, onClose };
}
