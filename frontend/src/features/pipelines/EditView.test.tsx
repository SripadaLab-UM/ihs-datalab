it("keeps a draft on this computer, and what's typed but not kept survives a reload", async () => {
  const first = open();
  await type(R + "# more\n");
  expect(screen.getByText("changes not kept yet")).toBeInTheDocument();
  expect(readUnsaved("pe_1")).toEqual({ files: { [STEPS]: R + "# more\n" }, version: "v1" });
  first.unmount();
  open({ id: "pe_1" });
  expect(await screen.findByText(/Restored changes you hadn't kept yet/)).toBeInTheDocument();
  expect(source()).toHaveValue(R + "# more\n");
  fireEvent.click(screen.getByRole("button", { name: "Keep as a draft on this computer" }));
  await waitFor(() => expect(pipelinesApi.keepEdit).toHaveBeenCalledWith("pe_1", { [STEPS]: R + "# more\n" }, "v1"));
  expect(await screen.findByText("Kept on this computer (not shared).")).toBeInTheDocument();
  expect(readUnsaved("pe_1")).toBeNull();
});

it("checks the text as it's typed, as the proposal's check, and marks the lines", async () => {
  vi.mocked(pipelinesApi.checkEdit).mockImplementation(async (_id, _path, text) => ({
    findings: text.includes(".onLoad") ? [hook] : [],
  }));
  open();
  expect(await screen.findByText(/The check passes/)).toBeInTheDocument();
  await type(R + ".onLoad <- function(l, p) NULL\n");
  // Once the typing stops for a moment.
  await waitFor(
    () => expect(pipelinesApi.checkEdit).toHaveBeenLastCalledWith("pe_1", STEPS, R + ".onLoad <- function(l, p) NULL\n"),
    { timeout: CHECK_DELAY_MS * 4 },
  );
  expect(await screen.findByTestId("diagnostic")).toHaveTextContent("2: .onLoad runs whenever the package is loaded");
  expect(screen.getByText(/The check: 1 to confirm/)).toBeInTheDocument();
  // Save & share waits for the person to confirm it.
  const save = screen.getByRole("button", { name: "Save & share" });
  expect(save).toBeDisabled();
  fireEvent.click(screen.getByRole("checkbox", { name: /steps.R:2.*it should run there/ }));
  expect(save).toBeEnabled();
});

